-- 1. Milestone Messages (Negotiation Chat)
CREATE TABLE IF NOT EXISTS milestone_messages (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    milestone_id UUID NOT NULL REFERENCES milestones(id) ON DELETE CASCADE,
    sender_id UUID REFERENCES users(id) ON DELETE SET NULL, -- Null if sent by AI/System
    sender_role VARCHAR(20) NOT NULL CHECK (sender_role IN ('client', 'developer', 'ai')),
    content TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_milestone_messages_milestone_id ON milestone_messages(milestone_id);

-- Enable RLS for real-time security
